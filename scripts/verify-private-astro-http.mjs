#!/usr/bin/env node
/**
 * Optional owner-controlled local HTTP verification for VirgoStars Astro masks.
 * The only persistent inputs are an already extracted, privately authorized
 * overlay root and its manifest/approval. No private assets are modified,
 * copied into the repo, uploaded, or included in Git outputs.
 *
 * Usage:
 * node scripts/verify-private-astro-http.mjs \
 *   --overlay-root /private/pack/public/assets \
 *   --overlay-manifest /private/pack/manifest.json \
 *   --overlay-approval /private/pack/private-astro-approval.json
 */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { once } from 'node:events';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createAssetServer } from './serve-local-assets.mjs';

const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const BASE_PATH='img/qa/synthetic-local.svg';

/** Verify the same HTTP server used by the demo, using a *synthetic* base pack. */
export async function verifyPrivateAstroHttp({overlayRoot,overlayManifest,overlayApproval}) {
  const temporary=mkdtempSync(join(tmpdir(),'astro-http-private-qa-'));
  const base=join(temporary,'public','assets');
  const source=Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 2 2"><circle cx="1" cy="1" r="1"/></svg>');
  const synthetic=join(base,BASE_PATH);
  mkdirSync(dirname(synthetic),{recursive:true});
  writeFileSync(synthetic,source);
  const baseManifest={schemaVersion:1,assets:[{
    path:BASE_PATH,bytes:source.length,sha256:sha256(source),status:'approved',
    rightsHolder:'Original synthetic test fixture',
    permissionBasis:'Generated by this QA script; not third-party imagery',
    approvalEvidence:'scripts/verify-private-astro-http.mjs',
  }]};
  let server;
  try {
    server=createAssetServer({
      root:base,manifest:baseManifest,
      astroOverlayRoot:overlayRoot,astroOverlayManifest:overlayManifest,
      astroOverlayApproval:overlayApproval,
    });
    server.listen(0,'127.0.0.1');
    await once(server,'listening');
    const url='http://127.0.0.1:'+server.address().port;
    let passed=0;
    for (const record of overlayManifest.assets) {
      const response=await fetch(url+'/assets/'+record.maskPath);
      assert.equal(response.status,200,'Private mask HTTP status: '+record.id);
      assert.equal(response.headers.get('content-type'),'image/png','Private mask MIME: '+record.id);
      const data=Buffer.from(await response.arrayBuffer());
      assert.equal(sha256(data),record.maskSha256,'Private mask SHA-256: '+record.id);
      passed++;
    }
    // Use the first approved mask for HTTP protocol checks without mutation.
    const approved=url+'/assets/'+overlayManifest.assets[0].maskPath;
    const head=await fetch(approved,{method:'HEAD'});
    assert.equal(head.status,200);
    assert.equal((await head.arrayBuffer()).byteLength,0);
    const baseResult=await fetch(url+'/assets/'+BASE_PATH);
    assert.equal(baseResult.status,200);
    assert.equal(sha256(Buffer.from(await baseResult.arrayBuffer())),sha256(source));
    assert.equal((await fetch(url+'/assets/img/virgostars-astro/masks/never-approved.png')).status,404);
    assert.equal((await fetch(approved,{headers:{Origin:'https://invalid.example'}})).status,403);
    assert.equal((await fetch(approved,{method:'POST'})).status,405);
    assert.equal((await fetch(approved,{method:'OPTIONS'})).status,204);
    return {masksVerified:passed,httpChecks:6,mode:'localhost-private-preview-only'};
  } finally {
    if(server)await new Promise(resolve=>server.close(resolve));
    rmSync(temporary,{recursive:true,force:true});
  }
}

function parseArguments(args) {
  const expected=new Set(['--overlay-root','--overlay-manifest','--overlay-approval']);
  const result={};
  if(args.length!==6)throw new Error('Expected --overlay-root, --overlay-manifest and --overlay-approval');
  for(let i=0;i<args.length;i+=2) {
    if(!expected.has(args[i]) || !args[i+1] || Object.hasOwn(result,args[i]))
      throw new Error('Invalid or repeated private Astro QA argument: '+String(args[i]));
    result[args[i]]=args[i+1];
  }
  if(Object.keys(result).length!==3)throw new Error('All three private Astro QA paths are required');
  return {
    overlayRoot:resolve(result['--overlay-root']),
    overlayManifest:JSON.parse(readFileSync(result['--overlay-manifest'],'utf8')),
    overlayApproval:JSON.parse(readFileSync(result['--overlay-approval'],'utf8')),
  };
}

if(process.argv[1] && resolve(process.argv[1])===resolve(fileURLToPath(import.meta.url))) {
  try {
    const result=await verifyPrivateAstroHttp(parseArguments(process.argv.slice(2)));
    console.log('PRIVATE ASTRO HTTP QA PASS: '+result.masksVerified+' masks and '+result.httpChecks+' HTTP checks');
  } catch(error) {
    console.error('PRIVATE ASTRO HTTP QA FAIL: '+error.message);
    process.exitCode=1;
  }
}
